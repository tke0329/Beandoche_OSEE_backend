ALTER TABLE garment ADD COLUMN material_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN'
    CHECK (material_status IN ('UNKNOWN', 'KNOWN'));

CREATE TABLE garment_variant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    garment_id BIGINT NOT NULL REFERENCES garment(id),
    color_name VARCHAR(100) NOT NULL CHECK (btrim(color_name) <> ''),
    color_code VARCHAR(100) NOT NULL CHECK (btrim(color_code) <> ''),
    color_hex VARCHAR(7) CHECK (color_hex ~ '^#[0-9A-Fa-f]{6}$'),
    thumbnail_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,
    UNIQUE (garment_id, color_code)
);

CREATE TABLE garment_size (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    garment_variant_id BIGINT NOT NULL REFERENCES garment_variant(id),
    size_label VARCHAR(50) NOT NULL CHECK (btrim(size_label) <> ''),
    sort_order INTEGER NOT NULL DEFAULT 0,
    sku VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(sku) <> ''),
    is_available BOOLEAN NOT NULL DEFAULT true,
    UNIQUE (garment_variant_id, size_label)
);

INSERT INTO garment_variant (garment_id, color_name, color_code, thumbnail_url)
SELECT id, '기본', 'DEFAULT', thumbnail_url FROM garment;

CREATE FUNCTION create_default_garment_variant() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO garment_variant (garment_id, color_name, color_code, thumbnail_url)
    VALUES (NEW.id, '기본', 'DEFAULT', NEW.thumbnail_url);
    RETURN NEW;
END;
$$;
CREATE TRIGGER tr_garment_default_variant AFTER INSERT ON garment
    FOR EACH ROW EXECUTE FUNCTION create_default_garment_variant();

CREATE TABLE material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(code) <> ''),
    name VARCHAR(100) NOT NULL CHECK (btrim(name) <> '')
);

CREATE TABLE garment_material (
    garment_id BIGINT NOT NULL REFERENCES garment(id),
    material_id BIGINT NOT NULL REFERENCES material(id),
    percentage NUMERIC(5,2) NOT NULL CHECK (percentage > 0 AND percentage <= 100),
    PRIMARY KEY (garment_id, material_id)
);

CREATE FUNCTION check_garment_material_total(product_id BIGINT) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM garment WHERE id = product_id AND material_status = 'KNOWN')
       AND (SELECT COALESCE(SUM(percentage), 0) FROM garment_material WHERE garment_id = product_id) <> 100 THEN
        RAISE EXCEPTION 'Known material composition must total 100' USING ERRCODE = '23514';
    END IF;
END;
$$;

CREATE FUNCTION validate_garment_material_total() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'garment' THEN
        PERFORM check_garment_material_total(NEW.id);
    ELSE
        IF TG_OP <> 'INSERT' THEN
            PERFORM check_garment_material_total(OLD.garment_id);
        END IF;
        IF TG_OP <> 'DELETE' THEN
            PERFORM check_garment_material_total(NEW.garment_id);
        END IF;
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER ck_garment_material_total
    AFTER INSERT OR UPDATE ON garment DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION validate_garment_material_total();
CREATE CONSTRAINT TRIGGER ck_garment_material_share_total
    AFTER INSERT OR UPDATE OR DELETE ON garment_material DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION validate_garment_material_total();

CREATE TABLE measurement_definition (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(code) <> ''),
    name VARCHAR(100) NOT NULL CHECK (btrim(name) <> ''),
    default_unit VARCHAR(20) NOT NULL CHECK (btrim(default_unit) <> ''),
    measurement_basis VARCHAR(20) NOT NULL
        CHECK (measurement_basis IN ('LENGTH', 'FLAT_WIDTH', 'CIRCUMFERENCE', 'WEIGHT')),
    description TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE category_measurement (
    category_id BIGINT NOT NULL REFERENCES category(id),
    measurement_definition_id BIGINT NOT NULL REFERENCES measurement_definition(id),
    is_required BOOLEAN NOT NULL DEFAULT false,
    display_order INTEGER NOT NULL DEFAULT 0,
    fit_analysis_enabled BOOLEAN NOT NULL DEFAULT false,
    min_value_mm NUMERIC(12,3),
    max_value_mm NUMERIC(12,3),
    PRIMARY KEY (category_id, measurement_definition_id),
    CHECK ((min_value_mm IS NULL AND max_value_mm IS NULL)
        OR (min_value_mm IS NOT NULL AND max_value_mm IS NOT NULL
            AND min_value_mm > 0 AND max_value_mm >= min_value_mm))
);

CREATE TABLE size_measurement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    garment_size_id BIGINT NOT NULL REFERENCES garment_size(id),
    measurement_definition_id BIGINT NOT NULL REFERENCES measurement_definition(id),
    value_mm NUMERIC(12,3) NOT NULL CHECK (value_mm > 0),
    source VARCHAR(30) NOT NULL
        CHECK (source IN ('BRAND_PROVIDED', 'DIRECT_MEASUREMENT', 'USER_PROVIDED', 'ESTIMATED')),
    measured_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (garment_size_id, measurement_definition_id)
);

CREATE FUNCTION check_length_measurement_unit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM measurement_definition
        WHERE id = NEW.measurement_definition_id AND measurement_basis <> 'WEIGHT' AND default_unit = 'mm') THEN
        RAISE EXCEPTION 'value_mm supports only length measurements in mm' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER ck_size_measurement_unit BEFORE INSERT OR UPDATE ON size_measurement
    FOR EACH ROW EXECUTE FUNCTION check_length_measurement_unit();

CREATE FUNCTION protect_measurement_unit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.measurement_basis = 'WEIGHT' OR NEW.default_unit <> 'mm')
       AND EXISTS (SELECT 1 FROM size_measurement WHERE measurement_definition_id = NEW.id) THEN
        RAISE EXCEPTION 'Existing length measurements require mm units' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER ck_measurement_definition_unit BEFORE UPDATE ON measurement_definition
    FOR EACH ROW EXECUTE FUNCTION protect_measurement_unit();
