CREATE TABLE social_unlink_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    provider VARCHAR(20) NOT NULL CHECK (provider IN ('GOOGLE', 'KAKAO')),
    provider_user_id VARCHAR(255),
    status VARCHAR(30) NOT NULL CHECK (status IN ('PENDING', 'RETRY', 'CONFIG_REQUIRED', 'USER_ACTION_REQUIRED', 'COMPLETED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error_code VARCHAR(60),
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_social_unlink_task_pending ON social_unlink_task(next_attempt_at)
    WHERE status IN ('PENDING', 'RETRY', 'CONFIG_REQUIRED');
CREATE UNIQUE INDEX uk_social_unlink_task_identity ON social_unlink_task(provider, provider_user_id)
    WHERE provider_user_id IS NOT NULL AND status <> 'COMPLETED';
